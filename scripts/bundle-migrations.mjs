/**
 * Concatenates the migrations, in order, into one file that can be pasted into
 * the Supabase SQL editor. For projects where the CLI is not linked and
 * `supabase db push` is not an option.
 *
 * The bundle is made re-runnable on the way out. A project that has already
 * had some of these applied is the normal case, not the exception: the schema
 * grows between pastes, and the person running it has no way to know which
 * files landed last time. Stopping at `type "member_role" already exists`
 * leaves them with no path forward short of reading the SQL themselves.
 *
 * The migrations keep their plain form, because `supabase db push` applies each
 * one exactly once and guards there would only be noise. The guards belong to
 * the paste-in path, which is this file's job.
 *
 * Regenerate after adding a migration: npm run db:bundle
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Rewrites the statements Postgres offers no `if not exists` for, so a second
 * run is a no op instead of an error. Everything else in these migrations is
 * already repeatable: `create or replace`, `add column if not exists`, `grant`,
 * and `comment on` can all be issued twice.
 */
function makeRepeatable(sql) {
  return (
    sql
      // `create type` has no guard of its own, and enums are all one line here.
      .replace(
        /^create type (\w+) as enum \(([^;]*)\);/gm,
        (_, name, values) =>
          `do $do$ begin\n  create type ${name} as enum (${values});\nexception when duplicate_object then null;\nend $do$;`
      )
      .replace(/^create table (?!if not exists)/gm, "create table if not exists ")
      // A view redefined with the identical body is a no op, and every later
      // migration that reshapes one already says `or replace` for itself.
      .replace(/^create view /gm, "create or replace view ")
      .replace(
        /^create (unique )?index (?!if not exists)/gm,
        (_, unique) => `create ${unique ?? ""}index if not exists `
      )
      // Triggers and policies take a drop first. The table name can sit on the
      // line after the name, so the match runs to the first `on <table>`.
      .replace(
        /^create trigger\s+(\w+)[\s\S]*?\bon\s+([\w.]+)/gm,
        (match, name, table) =>
          `drop trigger if exists ${name} on ${table};\n${match}`
      )
      .replace(
        /^create policy\s+("[^"]*"|\w+)[\s\S]*?\bon\s+([\w.]+)/gm,
        (match, name, table) =>
          `drop policy if exists ${name} on ${table};\n${match}`
      )
      // `add constraint` has no guard either, and the constraint is identical
      // on a second run, so dropping it first lands in the same place.
      .replace(
        /^alter table (\w+)\n(\s*)add constraint (\w+)/gm,
        (_, table, indent, name) =>
          `alter table ${table} drop constraint if exists ${name};\n` +
          `alter table ${table}\n${indent}add constraint ${name}`
      )
      // The one seeded insert without a conflict clause of its own.
      .replace(
        /^(insert into plan_limits[\s\S]*?);$/gm,
        "$1\non conflict (plan) do nothing;"
      )
  );
}

const dir = path.join(process.cwd(), "supabase", "migrations");
const files = (await readdir(dir)).filter((f) => f.endsWith(".sql")).sort();

const parts = [
  "-- Charta Home · all migrations, in order.",
  "-- Generated by scripts/bundle-migrations.mjs. Do not edit by hand.",
  "-- Paste into the Supabase SQL editor, then run seed.sql.",
  "--",
  "-- Safe to run more than once: a project that already has some of this",
  "-- applied will skip what it has and add only what is missing.",
  "",
];

const bodies = [];
for (const file of files) {
  bodies.push({
    file,
    sql: makeRepeatable((await readFile(path.join(dir, file), "utf8")).trim()),
  });
}

// Most policies here are created from a loop over a table list, where the
// statement only exists as a string at run time and no textual guard can reach
// it. Rather than rewrite that, the bundle clears the policies on its own
// tables first and lets the migrations below put every one of them back.
//
// Scoped to the tables this bundle creates, so nothing else in the project is
// touched, and row level security stays enabled the whole time: a table with
// no policy denies every request, so the gap fails closed rather than open.
const owned = [
  ...new Set(
    bodies.flatMap(({ sql }) =>
      [...sql.matchAll(/^create table if not exists (\w+)/gm)].map((m) => m[1])
    )
  ),
].sort();

// The views need the same treatment for a different reason. A later migration
// reshapes one an earlier migration defined, and `create or replace view`
// refuses to drop a column, so on a second run the earlier definition collides
// with the later one already in place. Dropping them first means each is built
// once more from scratch, ending at the same shape either way. Cascade because
// one view is built on another, and both are recreated below.
const ownedViews = [
  ...new Set(
    bodies.flatMap(({ sql }) =>
      [...sql.matchAll(/^create or replace view (\w+)/gm)].map((m) => m[1])
    )
  ),
].sort();

// Functions need clearing for a subtler reason: one of them gained a parameter
// in a later migration, and re-running leaves both signatures defined. Two
// overloads make a bare `grant execute on function name` ambiguous, and the
// paste fails on a statement that looks unrelated to the cause. Dropping by
// resolved signature removes every overload whatever its arguments are.
// Cascade because triggers and policies are built on these, and both are
// recreated below.
const ownedFunctions = [
  ...new Set(
    bodies.flatMap(({ sql }) =>
      [...sql.matchAll(/^create (?:or replace )?function (?:public\.)?(\w+)\s*\(/gm)].map(
        (m) => m[1]
      )
    )
  ),
].sort();

parts.push(
  `-- ${"=".repeat(70)}`,
  "-- Clear what this bundle owns and rebuilds, so it can be run again",
  `-- ${"=".repeat(70)}`,
  "",
  ...ownedViews.map((v) => `drop view if exists ${v} cascade;`),
  "",
  "do $do$",
  "declare f record;",
  "begin",
  "  for f in",
  "    select p.oid::regprocedure as sig",
  "    from pg_proc p join pg_namespace n on n.oid = p.pronamespace",
  "    where n.nspname = 'public'",
  `      and p.proname = any (array[${ownedFunctions.map((f) => `'${f}'`).join(", ")}])`,
  "  loop",
  "    execute format('drop function if exists %s cascade', f.sig);",
  "  end loop;",
  "end $do$;",
  "",
  "do $do$",
  "declare p record;",
  "begin",
  "  for p in",
  "    select tablename, policyname from pg_policies",
  "    where schemaname = 'public'",
  `      and tablename = any (array[${owned.map((t) => `'${t}'`).join(", ")}])`,
  "  loop",
  "    execute format('drop policy %I on public.%I', p.policyname, p.tablename);",
  "  end loop;",
  "end $do$;",
  ""
);

for (const { file, sql } of bodies) {
  parts.push(
    `-- ${"=".repeat(70)}`,
    `-- ${file}`,
    `-- ${"=".repeat(70)}`,
    "",
    sql,
    ""
  );
}

const out = path.join(process.cwd(), "supabase", "bundle.sql");
await writeFile(out, parts.join("\n") + "\n");
console.log(`bundled ${files.length} migrations into supabase/bundle.sql`);
for (const f of files) console.log(`  ${f}`);
